/* ---------- Демонстрации в шапке ---------- */
function initHeroDemos() {
  const box = $('#heroDemos');
  const data = RC.makeDataset(8, { lightDiverse: true }, 3);
  data.scenes.forEach((sc) => {
    const c = h('canvas', { 'aria-hidden': 'true' });
    box.append(c);
    requestAnimationFrame(() => SceneView.render(c, sc.scene, { demoPath: sc.states.map((s) => s.g), color: '#eb6834' }));
  });
}

